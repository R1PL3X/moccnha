-- 1. TẠO BẢNG DANH MỤC (categories)
CREATE TABLE IF NOT EXISTS categories (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL UNIQUE,
    slug TEXT NOT NULL UNIQUE,
    icon TEXT
);

-- 2. TẠO BẢNG SẢN PHẨM (products)
CREATE TABLE IF NOT EXISTS products (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title TEXT NOT NULL,
    full_title TEXT,
    category TEXT NOT NULL,
    collection TEXT,
    price BIGINT NOT NULL,
    original_price BIGINT NOT NULL,
    discount_percent INT DEFAULT 0,
    rating REAL DEFAULT 5.0,
    review_count INT DEFAULT 0,
    sold_count INT DEFAULT 0,
    image TEXT NOT NULL,
    detail_image TEXT,
    gallery JSONB DEFAULT '[]'::jsonb,
    colors JSONB DEFAULT '[]'::jsonb,
    highlights JSONB DEFAULT '[]'::jsonb,
    is_bestseller INT DEFAULT 0,
    is_promo INT DEFAULT 0,
    description TEXT,
    material TEXT,
    dimensions TEXT,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 3. TẠO BẢNG NGƯỜI DÙNG (users)
CREATE TABLE IF NOT EXISTS users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fullname TEXT NOT NULL,
    email TEXT UNIQUE NOT NULL,
    phone TEXT,
    password TEXT NOT NULL,
    role TEXT DEFAULT 'customer',
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 4. TẠO BẢNG ĐƠN HÀNG (orders)
CREATE TABLE IF NOT EXISTS orders (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT REFERENCES users(id) ON DELETE SET NULL,
    order_code TEXT UNIQUE NOT NULL,
    customer_name TEXT NOT NULL,
    customer_phone TEXT NOT NULL,
    customer_email TEXT,
    customer_address TEXT NOT NULL,
    payment_method TEXT DEFAULT 'COD',
    note TEXT,
    items JSONB NOT NULL,
    total_amount BIGINT NOT NULL,
    status TEXT DEFAULT 'pending', -- pending, confirmed, shipping, completed, cancelled
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 5. TẠO BẢNG YÊU CẦU BÁO GIÁ DỰ ÁN (quotes)
CREATE TABLE IF NOT EXISTS quotes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fullname TEXT NOT NULL,
    phone TEXT NOT NULL,
    email TEXT,
    project_type TEXT,
    note TEXT,
    status TEXT DEFAULT 'pending', -- pending, contacted, completed, cancelled
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- ==============================================================================
-- THIẾT LẬP ROW LEVEL SECURITY (RLS) - Cho phép đọc và ghi từ website
-- ==============================================================================
ALTER TABLE categories ENABLE ROW LEVEL SECURITY;
ALTER TABLE products ENABLE ROW LEVEL SECURITY;
ALTER TABLE orders ENABLE ROW LEVEL SECURITY;
ALTER TABLE users ENABLE ROW LEVEL SECURITY;
ALTER TABLE quotes ENABLE ROW LEVEL SECURITY;

-- Cho phép mọi người (khách) đọc danh mục và sản phẩm công khai
DROP POLICY IF EXISTS "Public read categories" ON categories;
CREATE POLICY "Public read categories" ON categories FOR SELECT USING (true);

DROP POLICY IF EXISTS "Public read products" ON products;
CREATE POLICY "Public read products" ON products FOR SELECT USING (true);

-- Cho phép thêm đơn hàng và xem đơn hàng
DROP POLICY IF EXISTS "Enable insert for orders" ON orders;
CREATE POLICY "Enable insert for orders" ON orders FOR INSERT WITH CHECK (true);

DROP POLICY IF EXISTS "Enable select for orders" ON orders;
CREATE POLICY "Enable select for orders" ON orders FOR SELECT USING (true);

DROP POLICY IF EXISTS "Enable update for orders" ON orders;
CREATE POLICY "Enable update for orders" ON orders FOR UPDATE USING (true);

-- Cho phép gửi và quản lý yêu cầu báo giá
DROP POLICY IF EXISTS "Enable all for quotes" ON quotes;
CREATE POLICY "Enable all for quotes" ON quotes FOR ALL USING (true);

DROP POLICY IF EXISTS "Enable select for orders" ON orders;
CREATE POLICY "Enable select for orders" ON orders FOR SELECT USING (true);

DROP POLICY IF EXISTS "Enable update for orders" ON orders;
CREATE POLICY "Enable update for orders" ON orders FOR UPDATE USING (true);

-- Cho phép đọc/ghi users
DROP POLICY IF EXISTS "Enable all for users" ON users;
CREATE POLICY "Enable all for users" ON users FOR ALL USING (true);

-- Cho phép admin thêm/sửa/xóa products
DROP POLICY IF EXISTS "Enable all for products" ON products;
CREATE POLICY "Enable all for products" ON products FOR ALL USING (true);

